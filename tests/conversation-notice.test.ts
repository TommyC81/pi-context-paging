import assert from "node:assert/strict";
import test from "node:test";
import { estimateTokens } from "@earendil-works/pi-coding-agent";
import type { HistoryItem } from "../src/history.ts";
import { selectContext, type ContextSelection, type ContextSelectionInput } from "../src/context-policy.ts";

type Entry = { id?: string; message: any; results?: any[] };

let clock = 1;
const userEntry = (id: string, content: unknown): Entry => ({ id, message: { role: "user", content, timestamp: clock++ } });
const replyEntry = (id: string, text: string): Entry => ({
	id, message: { role: "assistant", content: [{ type: "text", text }], stopReason: "stop", timestamp: clock++ },
});
const customEntry = (content: string): Entry => ({
	message: { role: "custom", customType: "wake", content, display: true, timestamp: clock++ },
});
// One tool exchange whose output costs about outputCharacters / 4 tokens.
const workEntry = (id: string, outputCharacters: number, text?: string): Entry => {
	const callId = `${id}-call`;
	return {
		id,
		message: {
			role: "assistant",
			content: [...(text ? [{ type: "text", text }] : []), { type: "toolCall", id: callId, name: "bash", arguments: { command: "make" } }],
			stopReason: "toolUse",
			timestamp: clock++,
		},
		results: [{
			role: "toolResult", toolCallId: callId, toolName: "bash",
			content: [{ type: "text", text: `${id} output ${"x".repeat(outputCharacters)}` }], isError: false, timestamp: clock++,
		}],
	};
};
const turn = (n: number, outputCharacters = 100_000, request: unknown = `U${n} request`): Entry[] => [
	userEntry(`u${n}`, request), workEntry(`w${n}`, outputCharacters), replyEntry(`r${n}`, `R${n} final reply`),
];

function session(entries: readonly Entry[], omittedIds: readonly string[] = []) {
	const messages = entries.flatMap((entry) => [entry.message, ...(entry.results ?? [])]);
	const items: HistoryItem[] = entries
		.filter((entry) => entry.id !== undefined && !omittedIds.includes(entry.id))
		.map((entry, sequence) => entry.message.role === "user"
			? { id: entry.id!, kind: "user", sequence, timestamp: "2026-10-30T00:00:00.000Z", userMessage: entry.message }
			: {
				id: entry.id!, kind: "modelTurn", sequence, timestamp: "2026-10-30T00:00:00.000Z",
				assistantMessage: entry.message, toolResults: entry.results ?? [],
				metadata: { tools: entry.results ? ["bash"] : [], files: [], failed: false },
			});
	return { messages, items };
}

const select = (value: ReturnType<typeof session>, options: Partial<ContextSelectionInput> = {}) => selectContext({
	messages: value.messages,
	systemPrompt: "resident prompt",
	activeTools: [],
	modelContextWindow: 400_000,
	tokenBudget: 100_000,
	trimToTokens: 60_000,
	rawHistoryItems: value.items,
	...options,
});

function noticeText(selection: ContextSelection): string {
	const first = selection.messages[0] as any;
	assert.equal(typeof first.content, "string");
	assert.match(first.content, /^\[Context paging notice — generated by the extension\]/);
	return first.content;
}
const retainedText = (selection: ContextSelection) => JSON.stringify(selection.messages.slice(1));
const inOrder = (text: string, ...values: string[]) => {
	const indexes = values.map((value) => text.indexOf(value));
	assert.equal(indexes.every((index) => index >= 0), true, `missing one of ${values.join(", ")}`);
	assert.deepEqual([...indexes].sort((a, b) => a - b), indexes, `out of order: ${values.join(", ")}`);
};

test("copies evicted user requests and the newest final replies into the paging notice", () => {
	const selection = select(session([
		...[1, 2, 3, 4, 5, 6].flatMap((n) => turn(n)),
		userEntry("active", "ACTIVE request"),
	]));
	const notice = noticeText(selection);
	const retained = retainedText(selection);

	assert.equal(selection.mode, "paged");
	for (const n of [1, 2, 3, 4]) {
		assert.equal(retained.includes(`U${n} request`), false, `U${n} should leave the retained messages`);
	}
	assert.equal(retained.includes("U5 request"), true);
	// R4 is the reply that the oldest retained request, U5, answered.
	inOrder(notice, 'historyId "u1"', "U1 request", "U2 request", "R2 final reply", "U3 request", "R3 final reply",
		'historyId "u4"', "U4 request", 'historyId "r4"', "R4 final reply");
	assert.equal(notice.includes("R1 final reply"), false, "only the newest three evicted replies are kept");
	assert.equal(notice.includes("w2 output"), false, "tool output stays out of the conversation record");
	assert.equal(selection.estimatedTokens <= 60_000, true, "the selector counts the larger notice");
});

test("keeps turns evicted at earlier cuts when a remembered cut advances", () => {
	const firstEntries = [...[1, 2, 3, 4, 5, 6].flatMap((n) => turn(n)), userEntry("active-1", "ACTIVE ONE request")];
	const first = select(session(firstEntries));
	assert.equal(noticeText(first).includes("U1 request"), true);

	const secondEntries = [
		...firstEntries,
		workEntry("active-1-work", 100_000), replyEntry("active-1-reply", "ACTIVE ONE reply"),
		...turn(7), ...turn(8),
		userEntry("active-2", "ACTIVE TWO request"),
	];
	const second = select(session(secondEntries), { cutState: first.cutState });
	const notice = noticeText(second);

	assert.notEqual(second.cutState, first.cutState, "the cut advanced");
	inOrder(notice, "U1 request", "U4 request", "U5 request", "U6 request", "ACTIVE ONE request");
	assert.equal(retainedText(second).includes("U6 request"), false);

	const unchanged = select(session([...secondEntries, workEntry("active-2-work", 100)]), { cutState: second.cutState });
	assert.equal(noticeText(unchanged), notice, "the notice changes only when the cut advances");
});

test("leaves partial active-turn evictions out of the conversation record", () => {
	const selection = select(session([
		...turn(1, 100),
		userEntry("active", "ACTIVE request"),
		...[1, 2, 3, 4, 5, 6].map((step) => workEntry(`step-${step}`, 100_000, `STEP ${step} note`)),
	]));
	const notice = noticeText(selection);

	assert.equal(retainedText(selection).includes("ACTIVE request"), true);
	assert.equal(retainedText(selection).includes("STEP 1 note"), false);
	inOrder(notice, "U1 request", "R1 final reply");
	assert.equal(notice.includes("STEP 1 note"), false);
	assert.equal(notice.includes("ACTIVE request"), false);
});

test("includes only messages with recoverable history IDs", () => {
	const entries = [...[1, 2, 3, 4, 5, 6].flatMap((n) => turn(n)), userEntry("active", "ACTIVE request")];
	const partial = noticeText(select(session(entries, ["u2"])));
	assert.equal(partial.includes("U1 request"), true);
	assert.equal(partial.includes("U2 request"), false);

	const unavailable = noticeText(select(session(entries), { rawHistoryItems: undefined }));
	assert.equal(unavailable.includes("U1 request"), false);
});

test("shows the reply of an extension-started turn without its extension message", () => {
	const notice = noticeText(select(session([
		...turn(1),
		customEntry("EXTENSION WAKE payload"), workEntry("wake-work", 100_000), replyEntry("wake-reply", "WAKE final reply"),
		...turn(3), ...turn(4), ...turn(5),
		userEntry("active", "ACTIVE request"),
	])));

	inOrder(notice, "U1 request", "WAKE final reply", "U3 request");
	assert.equal(notice.includes("EXTENSION WAKE payload"), false);
});

test("shows user images as placeholders without image data", () => {
	const notice = noticeText(select(session([
		...turn(1, 100_000, [{ type: "text", text: "see screenshot" }, { type: "image", data: "SU1BR0VEQVRB", mimeType: "image/png" }]),
		...[2, 3, 4, 5, 6].flatMap((n) => turn(n)),
		userEntry("active", "ACTIVE request"),
	])));

	assert.equal(notice.includes("see screenshot\n[image]"), true);
	assert.equal(notice.includes("SU1BR0VEQVRB"), false);
});

test("clips long entries at a whole character and names the exact part to read", () => {
	const longRequest = `HEAD ${"y".repeat(5_994)}😀 TAIL_MARKER`;
	const longReply = `REPLY HEAD ${"z".repeat(10_000)} REPLY_TAIL`;
	const notice = noticeText(select(session([
		...turn(1, 100_000, longRequest), ...turn(2), ...turn(3),
		userEntry("u4", "U4 request"), workEntry("w4", 100_000), replyEntry("r4", longReply),
		...turn(5), ...turn(6),
		userEntry("active", "ACTIVE request"),
	])));

	assert.equal(notice.includes("HEAD"), true);
	assert.equal(notice.includes("TAIL_MARKER"), false);
	assert.equal(notice.includes("REPLY_TAIL"), false);
	assert.doesNotMatch(notice, /[\uD800-\uDBFF](?![\uDC00-\uDFFF])/u, "no lone high surrogate");
	assert.equal(notice.includes(`read_context_output(${JSON.stringify({ historyId: "u1", part: "/userMessage/content" })})`), true);
	assert.equal(notice.includes(`read_context_output(${JSON.stringify({ historyId: "r4", part: "/assistantMessage/content/0" })})`), true);
});

test("keeps the newest conversation within the section cap and counts omitted requests", () => {
	const turns = Array.from({ length: 14 }, (_, index) => index + 1);
	const notice = noticeText(select(session([
		...turns.flatMap((n) => turn(n, 40_000, `U${n} request ${"q".repeat(5_000)}`)),
		userEntry("active", "ACTIVE request"),
	])));

	const shown = turns.filter((n) => notice.includes(`U${n} request`));
	const evicted = turns.filter((n) => !shown.includes(n) && n <= Math.max(...shown));
	assert.equal(shown.length > 0, true);
	assert.equal(evicted.length > 0, true, "older requests fall outside the cap");
	assert.deepEqual(evicted, turns.slice(0, evicted.length), "omitted requests are the oldest ones");
	assert.match(notice, new RegExp(`\\b${evicted.length} earlier user messages? (is|are) not shown\\b`));
	assert.equal(notice.length < 32_000 + 2_000, true);

	const small = noticeText(select(session([
		...turns.flatMap((n) => turn(n, 4_000, `U${n} request ${"q".repeat(5_000)}`)),
		userEntry("active", "ACTIVE request"),
	]), { tokenBudget: 20_000, trimToTokens: 12_000 }));
	assert.equal(estimateTokens({ role: "user", content: small, timestamp: 0 }) <= 2_000 + 500, true, "the cap follows a small budget");
});

test("fits the conversation into the room the active request leaves instead of failing", () => {
	const selection = select(session([
		...[1, 2, 3].flatMap((n) => turn(n, 4_000, `U${n} request ${"q".repeat(3_000)}`)),
		userEntry("active", `ACTIVE request ${"a".repeat(4 * 98_000)}`),
	]));

	assert.equal(selection.estimatedTokens <= selection.budgetTokens, true);
	const notice = noticeText(selection);
	inOrder(notice, "U3 request", "R3 final reply");
	assert.equal(estimateTokens({ role: "user", content: notice, timestamp: 0 }) < 2_000, true, "the notice shrinks to the remaining room");
});

test("shrinks a remembered conversation when added instructions leave nothing else to evict", () => {
	const value = session([
		...[1, 2, 3, 4, 5].flatMap((n) => [
			userEntry(`u${n}`, `U${n} request ${"u".repeat(3_000)}`), replyEntry(`r${n}`, `R${n} final reply ${"r".repeat(3_000)}`),
		]),
		userEntry("active", `ACTIVE request ${"a".repeat(36_000)}`),
	]);
	const options = { tokenBudget: 10_000, trimToTokens: 6_000 };
	const first = select(value, options);
	assert.equal(retainedText(first).includes("R5 final reply"), false, "the cut leaves only the active request");
	assert.equal(noticeText(first).includes("R5 final reply"), true);

	// Outgoing-only extension instructions that still fit beside the plain notice.
	const instructions = { role: "user", content: `REQUEST INSTRUCTIONS ${"x".repeat(2_000)}`, timestamp: clock++ };
	const second = select({ messages: [...value.messages, instructions], items: value.items }, {
		...options, outgoingOnly: [...value.messages.map(() => false), true], cutState: first.cutState,
	});

	assert.equal(second.mode, "paged");
	assert.equal(second.estimatedTokens <= second.budgetTokens, true);
	assert.equal(noticeText(second).length < noticeText(first).length, true, "the copied conversation shrinks to the remaining room");
	assert.equal(retainedText(second).includes("REQUEST INSTRUCTIONS"), true);

	const third = select(value, { ...options, cutState: second.cutState });
	assert.equal(noticeText(third), noticeText(second), "the resized notice stays until the cut advances");
});
